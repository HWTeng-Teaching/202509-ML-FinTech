# ax.set_yscale('log')

plt.show()


# (f) PlotPower(xs, a): 針對給定的 x 序列與固定的 a，畫出 x 對 x**a
def PlotPower(xs, a, logx=False, logy=False, title=None):
    """
    xs: 可迭代的 x 值（例如 np.arange(1, 11)）
    a : 指數
    logx/logy: 是否將 x 或 y 軸用對數尺度
    title: 自訂圖標題（預設自動產生）
    """
    xs = np.asarray(xs)
    ys = np.array([Power3(x, a) for x in xs])

    fig, ax = plt.subplots()
    ax.plot(xs, ys, marker='o')
    ax.set_xlabel("x")
    ax.set_ylabel(f"x^{a}")
    if title is None:
        title = f"f(x) = x^{a}"
    ax.set_title(title)

    if logx:
        ax.set_xscale('log')
    if logy:
        ax.set_yscale('log')

    plt.show()

# 示範：畫出 x=1..10 的立方
PlotPower(np.arange(1, 11), 3)