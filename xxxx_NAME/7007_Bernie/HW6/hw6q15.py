# (a) Power(): 印出 2**3
def Power():
    print(2 ** 3)

# 測試
Power()  # 8


# (b) Power2(x, a): 印出 x**a
def Power2(x, a):
    print(x ** a)

# 測試
Power2(3, 8)  # 6561


# (c) 用 Power2() 計算 10**3、8**17、13**13
Power2(10, 3)   # 1000
Power2(8, 17)   # 2251799813685248
Power2(13, 13)  # 302875106592253


# (d) Power3(x, a): 回傳 x**a（不用印出，改成 return）
def Power3(x, a):
    result = x ** a
    return result

# 測試
val = Power3(2, 10)
print("Power3(2,10) =", val)  # 1024


# (e) 使用 Power3() 繪製 f(x) = x^2，x=1..10
import numpy as np
import matplotlib.pyplot as plt

xs = np.arange(1, 11)           # 1,2,...,10
ys = np.array([Power3(x, 2) for x in xs])

fig, ax = plt.subplots()
ax.plot(xs, ys, marker='o')
ax.set_xlabel("x")
ax.set_ylabel("x^2")
ax.set_title("f(x) = x^2 for x = 1..10")

# 可選：如果想要對數刻度，取消下列註解
